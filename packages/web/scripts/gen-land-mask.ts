// Rasterises Natural Earth land (world-atlas, public domain) into a 1-bit equirectangular mask for the landing
// globe, so the app ships its land data and never fetches it at runtime. Rerun with
// `pnpm --filter @zal/web gen:land`.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createRequire } from "node:module";

import { feature } from "topojson-client";

const WIDTH = 360;
const HEIGHT = 180;
const require = createRequire(import.meta.url);
const OUT = join(import.meta.dirname, "..", "lib", "globe", "land-mask.ts");

type Position = readonly number[];
type Ring = readonly Position[];
type Polygon = {
  readonly type: "Polygon";
  readonly coordinates: readonly Ring[];
};
type MultiPolygon = {
  readonly type: "MultiPolygon";
  readonly coordinates: readonly (readonly Ring[])[];
};
interface Shape {
  readonly rings: readonly Ring[];
  readonly box: readonly [number, number, number, number];
}

function inRing(lon: number, lat: number, ring: Ring): boolean {
  let inside = false;

  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i] as [number, number];
    const [xj, yj] = ring[j] as [number, number];

    if (
      yi > lat !== yj > lat &&
      lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
    ) {
      inside = !inside;
    }
  }

  return inside;
}

function shapesOf(geometry: Polygon | MultiPolygon): Shape[] {
  const polygons =
    geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;

  return polygons.map((rings) => {
    const outer = rings[0] ?? [];
    const lons = outer.map((p) => p[0] ?? 0);
    const lats = outer.map((p) => p[1] ?? 0);

    return {
      rings,
      box: [
        Math.min(...lons),
        Math.min(...lats),
        Math.max(...lons),
        Math.max(...lats),
      ],
    };
  });
}

const topology = JSON.parse(
  readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"),
);
const land = feature(topology, topology.objects.land) as unknown as {
  readonly features: readonly { readonly geometry: Polygon | MultiPolygon }[];
};
const shapes = land.features.flatMap((f) => shapesOf(f.geometry));
const bytes = new Uint8Array((WIDTH * HEIGHT) / 8);

for (let row = 0; row < HEIGHT; row++) {
  const lat = 90 - (row + 0.5) * (180 / HEIGHT);

  for (let col = 0; col < WIDTH; col++) {
    const lon = -180 + (col + 0.5) * (360 / WIDTH);
    const hit = shapes.some(
      ({ rings, box }) =>
        lon >= box[0] &&
        lon <= box[2] &&
        lat >= box[1] &&
        lat <= box[3] &&
        // Even-odd over every ring handles holes (lakes, inland seas).
        rings.filter((ring) => inRing(lon, lat, ring)).length % 2 === 1,
    );

    if (hit) {
      const index = row * WIDTH + col;

      bytes[index >> 3]! |= 1 << (index & 7);
    }
  }
}

writeFileSync(
  OUT,
  `// Generated by scripts/gen-land-mask.ts from Natural Earth 1:50m land (world-atlas). Do not edit.\n\n` +
    `/** Land as a 1-bit equirectangular mask: row 0 is 90°N, column 0 is 180°W, one bit per cell, LSB first. */\n` +
    `export const LAND_MASK = {\n  width: ${WIDTH},\n  height: ${HEIGHT},\n  base64:\n    "${Buffer.from(bytes).toString("base64")}",\n} as const;\n`,
);
console.log(`wrote ${OUT}`);
