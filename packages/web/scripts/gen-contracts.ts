// A JSON import widens every ABI string to `string`, so viem could not infer function names or arguments.
// Emitting `as const` TypeScript keeps them literal. Rerun with `pnpm --filter @zal/web gen:contracts` after the
// contracts change (`forge build`) or a redeploy writes packages/contracts/deployments/*.json.

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const CONTRACTS = join(import.meta.dirname, "..", "..", "contracts");
const OUT_DIR = join(import.meta.dirname, "..", "contracts");
const HEADER = "// Generated by scripts/gen-contracts.ts from packages/contracts. Do not edit.\n\n";

const ARTIFACTS = {
  mockUsdc: "MockUSDC",
  zalFactory: "ZalFactory",
  canvasAccount: "CanvasAccount",
  relationshipRegistry: "RelationshipRegistry",
  zalInvoice: "ZalInvoice",
  zalFundingPool: "ZalFundingPool",
  zalVault: "ZalVault",
} as const;

const DEPLOYMENT_ADDRESSES = [
  "owner",
  "keeper",
  "usdc",
  "factory",
  "registry",
  "invoices",
  "pool",
  "vault",
] as const;

interface Artifact {
  readonly abi: unknown[];
  readonly bytecode: `0x${string}`;
}

function readArtifact(name: string): Artifact {
  const path = join(CONTRACTS, "out", `${name}.sol`, `${name}.json`);
  const json: unknown = JSON.parse(readFileSync(path, "utf8"));
  if (typeof json !== "object" || json === null) throw new Error(`${path}: not an object`);
  const abi = Reflect.get(json, "abi");
  const bytecode: unknown = Reflect.get(Reflect.get(json, "bytecode") ?? {}, "object");
  if (!Array.isArray(abi)) throw new Error(`${path}: abi is not an array`);
  if (typeof bytecode !== "string" || !/^0x[0-9a-fA-F]+$/.test(bytecode) || bytecode.length < 4) {
    throw new Error(`${path}: bytecode.object is missing or not hex (unlinked libraries are not supported)`);
  }
  return { abi, bytecode: bytecode as `0x${string}` };
}

function readDeployments(): Record<string, Record<string, unknown>> {
  const dir = join(CONTRACTS, "deployments");
  const out: Record<string, Record<string, unknown>> = {};
  let files: string[] = [];
  try {
    files = readdirSync(dir).filter((f) => f.endsWith(".json"));
  } catch {
    return out;
  }
  for (const file of files) {
    const json: unknown = JSON.parse(readFileSync(join(dir, file), "utf8"));
    if (typeof json !== "object" || json === null) throw new Error(`${file}: not an object`);
    const value = json as Record<string, unknown>;
    const chainId = value.chainId;
    if (typeof chainId !== "number") throw new Error(`${file}: chainId is not a number`);
    const entry: Record<string, unknown> = { chainId, name: file.replace(/\.json$/, "") };
    for (const key of DEPLOYMENT_ADDRESSES) {
      const address = value[key];
      if (typeof address !== "string" || !/^0x[0-9a-fA-F]{40}$/.test(address)) {
        throw new Error(`${file}: "${key}" is missing or not an address`);
      }
      entry[key] = address;
    }
    for (const key of ["advanceRateBps", "annualFeeBps"] as const) {
      if (typeof value[key] !== "number") throw new Error(`${file}: "${key}" is not a number`);
      entry[key] = value[key];
    }
    out[String(chainId)] = entry;
  }
  return out;
}

/** The sandbox deploys with the same config file Deploy.s.sol reads, so its rates match a local deployment. */
function readLocalConfig(): Record<string, number | string> {
  const toml = readFileSync(join(CONTRACTS, "script", "config", "local.toml"), "utf8");
  const read = (section: string, key: string): string => {
    const body = toml.split(new RegExp(`^\\[${section}\\]$`, "m"))[1]?.split(/^\[/m)[0] ?? "";
    const match = new RegExp(`^${key}\\s*=\\s*"?([^"\\s#]+)"?`, "m").exec(body);
    if (match?.[1] === undefined) throw new Error(`local.toml: [${section}] ${key} is missing`);
    return match[1];
  };
  return {
    owner: read("roles", "owner"),
    keeper: read("roles", "keeper"),
    advanceRateBps: Number(read("pool", "advance_rate_bps")),
    annualFeeBps: Number(read("pool", "annual_fee_bps")),
  };
}

const artifacts = Object.entries(ARTIFACTS).map(([key, name]) => [key, readArtifact(name)] as const);

const abis =
  HEADER +
  artifacts
    .map(([key, a]) => `export const ${key}Abi = ${JSON.stringify(a.abi, null, 2)} as const;\n`)
    .join("\n");

const bytecode =
  HEADER +
  "// Creation bytecode, loaded only by the sandbox engine (a dynamic import), never by live mode.\n\n" +
  artifacts.map(([key, a]) => `export const ${key}Bytecode = "${a.bytecode}" as const;\n`).join("");

const deployments =
  HEADER +
  "// One entry per packages/contracts/deployments/*.json, keyed by chain id.\n\n" +
  `export const deployments = ${JSON.stringify(readDeployments(), null, 2)} as const;\n\n` +
  "// packages/contracts/script/config/local.toml, the config the sandbox deploys with.\n" +
  `export const localDeployConfig = ${JSON.stringify(readLocalConfig(), null, 2)} as const;\n`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, "abis.ts"), abis);
writeFileSync(join(OUT_DIR, "bytecode.ts"), bytecode);
writeFileSync(join(OUT_DIR, "deployments.ts"), deployments);
console.log(`wrote contracts/abis.ts, contracts/bytecode.ts, contracts/deployments.ts (${artifacts.length} contracts)`);
