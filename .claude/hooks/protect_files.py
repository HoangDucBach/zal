#!/usr/bin/env python3
"""PreToolUse hook (Read, Edit, Write, MultiEdit, NotebookEdit, Grep, Glob): protect sensitive files.

- Credentials (.env, keys, ~/.ssh ...): blocked for every tool. `.env.example` and similar
  templates stay readable and editable, because they document the variables a project expects.
- Git internals and lockfiles: blocked for writes. Lockfiles must be regenerated by the package
  manager; a hand edit usually breaks integrity hashes.
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import block, fail_closed, is_secret_path, read_event  # noqa: E402

HOOK = "protect_files"
WRITE_TOOLS = {"Edit", "Write", "MultiEdit", "NotebookEdit"}
READ_TOOLS = {"Read", "Grep", "Glob"}
LOCKFILES = {
    "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lockb", "bun.lock", "poetry.lock",
    "uv.lock", "Pipfile.lock", "Cargo.lock", "go.sum", "Gemfile.lock", "composer.lock",
}


def target_paths(tool_name, tool_input):
    if tool_name in ("Grep", "Glob"):
        return [p for p in (tool_input.get("path"),) if p]
    return [p for p in (tool_input.get("file_path"), tool_input.get("notebook_path")) if p]


def main():
    with fail_closed(HOOK):
        event = read_event()
        tool = event.get("tool_name", "")
        if tool not in WRITE_TOOLS and tool not in READ_TOOLS:
            return
        cwd = event.get("cwd") or os.getcwd()
        for raw in target_paths(tool, event.get("tool_input") or {}):
            absolute = os.path.normpath(os.path.join(cwd, os.path.expanduser(raw)))
            # Check the path as written and where it really points (symlink to a secret).
            for candidate in {absolute, os.path.realpath(absolute)}:
                if is_secret_path(candidate):
                    block(
                        HOOK,
                        f"{os.path.basename(candidate)} holds credentials",
                        "Use .env.example or the config schema to learn which variables exist. "
                        "If you need a value, ask the user.",
                    )
            if tool in WRITE_TOOLS:
                parts = absolute.split(os.sep)
                if ".git" in parts[:-1]:
                    block(HOOK, "editing files inside .git/ can corrupt the repository", "Use git commands instead.")
                if os.path.basename(absolute) in LOCKFILES:
                    block(
                        HOOK,
                        f"{os.path.basename(absolute)} is a lockfile and must not be edited by hand",
                        "Change the dependency manifest and let the package manager regenerate the lockfile.",
                    )


if __name__ == "__main__":
    main()
